const NigerianStates = Object.keys(NigerianLGAs);

export default function Register() {
  const [username, setUsername] = useState('');
  const [password, setPassword] = useState('');
  const [confirmPassword, setConfirmPassword] = useState('');
  const [facilityName, setFacilityName] = useState('');
  const [state, setState] = useState('');
  const [lga, setLga] = useState('');
  const [loading, setLoading] = useState(false);
  const [facilities, setFacilities] = useState([]);
  const navigate = useNavigate();

  useEffect(() => {
    api.get('/facilities')
      .then(r => setFacilities(r.data))
      .catch(() => {}); // silent fail — dropdown will be empty
  }, []);

  const lgas = state ? NigerianLGAs[state] || [] : [];

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (!username) {
      toast.error('Username is required');
      return;
    }
    if (password !== confirmPassword) {
      toast.error('Passwords do not match');
      return;
    }
    if (!facilityName) {
      toast.error('Please select a facility');
      return;
    }
    if (!state) {
      toast.error('State is required');
      return;
    }
    if (!lga) {
      toast.error('LGA is required');
      return;
    }
    setLoading(true);
    try {
      const selectedFacility = facilities.find(f => String(f.id) === facilityName || f.name === facilityName);
      await api.post('/auth/register', {
        name: username,
        facility_name: selectedFacility?.name || facilityName,
        password,
        state,
        lga
      });
      toast.success('Account created successfully! Please log in.');
      navigate('/login');
    } catch (err) {
      toast.error(err.response?.data?.error || 'Registration failed');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="min-h-screen bg-gradient-to-br from-emerald-500 via-teal-500 to-blue-600 flex items-center justify-center p-4">
      <div className="w-full max-w-md">
        <div className="text-center mb-8">
          <div className="w-14 h-14 bg-teal-500 rounded-2xl flex items-center justify-center mx-auto mb-4 shadow-lg">
            <svg className="w-7 h-7 text-white" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2.5}>
              <path d="M19.428 15.428a2 2 0 00-1.022-.547l-2.387-.477a6 6 0 00-3.86.517l-.318.158a6 6 0 01-3.86.517L6.05 15.21a2 2 0 00-1.806.547M8 4h8l-1 1v5.172a2 2 0 00.586 1.414l5 5c1.26 1.26.367 3.414-1.415 3.414H4.828c-1.782 0-2.674-2.154-1.414-3.414l5-5A2 2 0 009 10.172V5L8 4z" />
            </svg>
          </div>
          <h1 className="text-2xl font-bold text-gray-900">LabTrack</h1>
          <p className="text-sm text-gray-500 mt-1">Create your account</p>
        </div>

        <div className="card p-8">
          <form onSubmit={handleSubmit} className="space-y-5">
            <div className="border-b pb-3 mb-1">
              <p className="text-xs text-gray-400 mb-3">Facility Information</p>
              <div className="space-y-4">
                <div>
                  <label className="label">Facility Name *</label>
                  <select className="input" value={facilityName} onChange={e => setFacilityName(e.target.value)} required>
                    <option value="">Select Facility...</option>
                    {facilities.map(f => (
                      <option key={f.id} value={f.name}>{f.name}</option>
                    ))}
                  </select>
                </div>
                <div>
                  <label className="label">State *</label>
                  <select className="input" value={state} onChange={e => { setState(e.target.value); setLga(''); }} required>
                    <option value="">Select State...</option>
                    {NigerianStates.map(s => <option key={s} value={s}>{s}</option>)}
                  </select>
                </div>
                <div>
                  <label className="label">LGA *</label>
                  <select className="input" value={lga} onChange={e => setLga(e.target.value)} required disabled={!state}>
                    <option value="">{state ? 'Select LGA...' : 'Select a state first'}</option>
                    {lgas.map(l => <option key={l} value={l}>{l}</option>)}
                  </select>
                </div>
              </div>
            </div>
            <div>
              <label className="label">Username</label>
              <input type="text" className="input" value={username} onChange={e => setUsername(e.target.value)} required placeholder="Choose a username" />
            </div>
            <div>
              <label className="label">Password</label>
              <input type="password" className="input" value={password} onChange={e => setPassword(e.target.value)} required />
            </div>
            <div>
              <label className="label">Confirm Password</label>
              <input type="password" className="input" value={confirmPassword} onChange={e => setConfirmPassword(e.target.value)} required />
            </div>
            <button type="submit" disabled={loading} className="btn btn-primary w-full justify-center py-2.5">
              {loading ? (
                <span className="flex items-center gap-2">
                  <svg className="w-4 h-4 animate-spin" fill="none" viewBox="0 0 24 24">
                    <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4" />
                    <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4z" />
                  </svg>
                  Creating account...
                </span>
              ) : 'Create Account'}
            </button>
          </form>
          <p className="text-center text-xs text-gray-400 mt-4">
            Already have an account? <Link to="/login" className="text-teal-600 hover:text-teal-700">Sign in</Link>
          </p>
          <p className="text-center text-xs text-gray-400 mt-2">
            <Link to="/" className="text-gray-500 hover:text-gray-700">Back to Home</Link>
          </p>
        </div>
      </div>
    </div>
  );
}